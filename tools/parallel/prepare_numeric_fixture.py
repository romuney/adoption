#!/usr/bin/env python3
"""Build isolated synthetic CH tables and execute NEW GP acceleration in PostgreSQL.

Requires LOCAL PA_DB, PGHOST/PGPORT/PA_PG and pinned dependencies. Not corporate ETL.
"""
import argparse
from collections import Counter
import json
import os
from pathlib import Path
import re
import sys
from verify_numbers import ROOT, load_stand
import yaml


def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--regenerate',action='store_true',help='Rebuild random legacy synthetic fixture and GP baseline')
    ap.add_argument('--output',type=Path,default=Path('/tmp/pa-next-gp-results.json'))
    args=ap.parse_args()
    if not os.environ.get('PA_DB') or os.environ.get('PGHOST','') not in ('127.0.0.1','localhost','/workspace/.cache/pa-next-pgsocket'):
        ap.error('Explicit local PA_DB and PGHOST required')
    stand=load_stand(); import gp
    if args.regenerate:
        stand.gen(); gp.run()
    nb=yaml.safe_load((ROOT/'Параллельный отчёт — pa_next/1. Helicopter — pa_next.yaml').read_text())
    paras=[p for p in nb['paragraphs'] if p.get('title','').startswith('PA NEXT · ускорение')]
    manifest=json.loads((ROOT/'Параллельный отчёт — pa_next/src/data-manifest.json').read_text())
    # Base tables are supplied by the established synthetic model. The separately
    # tested actual source event paragraph is NOT claimed to generate this fixture.
    table_names=json.loads(stand.S.query("SELECT name FROM system.tables WHERE database='prod_proteus' AND startsWith(name,'pa_') AND NOT startsWith(name,'pa_next_')",'JSON').bytes())['data']
    for item in table_names:
        old=item['name']; new=old.replace('pa_','pa_next_',1)
        stand.S.query('DROP TABLE IF EXISTS prod_proteus.'+new)
        stand.S.query("CREATE TABLE prod_proteus."+new+" ENGINE=MergeTree ORDER BY tuple() AS SELECT *, 'test-1' AS _pa_next_run FROM prod_proteus."+old)
    needed=sorted(set().union(*(set(re.findall(r'usr_cross_data\.(pa_next_\w+)',p['code'])) for p in paras))-{'pa_next_run'})
    for new in needed:
        old=new.replace('pa_next_','pa_',1)
        gp.ch_to_pg(old)
        gp.psql('DROP TABLE IF EXISTS usr_cross_data.'+new+'; CREATE TABLE usr_cross_data.'+new+" AS SELECT *, 'test-1'::text AS _pa_next_run FROM usr_cross_data."+old+'; ANALYZE usr_cross_data.'+new+';')
    gp.psql("DROP TABLE IF EXISTS usr_cross_data.pa_next_run; CREATE TABLE usr_cross_data.pa_next_run AS SELECT 'test-1'::text AS run_id;")
    for para in paras:
        gp.psql(gp.pg_text(para['code']))
        print('PASS executed',para['title'],flush=True)
    checked=[]
    for ex in manifest['exports']:
        name=ex['gp'].split('.')[-1]
        # Only accelerated tables are generated by these three paragraphs.
        if not any(re.search(r'(?i)create\s+(?:temp\s+)?table\s+(?:usr_cross_data\.)?'+re.escape(name)+r'\s+as',p['code']) for p in paras):
            continue
        count=gp.pg_to_ch(name,{'order':ex['options'].get('order_by_columns','tuple()'),'arr':ex['options'].get('array_type_cast',False)})
        old=name.replace('pa_next_','pa_',1)
        cols=[n for n,t in gp.ch_cols(old)]
        def rows(table):
            values=json.loads(stand.S.query('SELECT '+','.join(cols)+' FROM prod_proteus.'+table,'JSONCompact').bytes())['data']
            return Counter(json.dumps(row,ensure_ascii=False,sort_keys=True) for row in values)
        a,b=rows(old),rows(name)
        if a!=b:
            raise AssertionError('Stamped GP acceleration changed payload: '+name+'; missing '+str(list((a-b).elements())[:1])+' extra '+str(list((b-a).elements())[:1]))
        checked.append(dict(table=name,rows=count,status='passed'))
        print('PASS exact GP output',name,count,flush=True)
    stand.S.query('DROP TABLE IF EXISTS prod_proteus.pa_next_manifest')
    stand.S.query("CREATE TABLE prod_proteus.pa_next_manifest (run_id String,state String) ENGINE=MergeTree ORDER BY run_id")
    stand.S.query("INSERT INTO prod_proteus.pa_next_manifest VALUES ('test-1','ready')")
    report=dict(status='passed',checks=checked,scope='new stamped GP acceleration vs existing GP expressions on synthetic input; source event stage checked separately')
    args.output.write_text(json.dumps(report,ensure_ascii=False,indent=2)+'\n')

if __name__=='__main__':main()
