#!/usr/bin/env python3
"""Render actual candidate SQL outputs; verify 4 periods without changing business rows.

Input is generated by numeric review/export on the synthetic ClickHouse24.8 world.
Only per-browser-session request-nonce metadata is replaced. No SQL connection is
opened, so the check can run while the numeric matrix owns its database handle.
"""
import argparse,copy,hashlib,json,re
from datetime import date,timedelta
from pathlib import Path
from playwright.sync_api import sync_playwright
from test_ui import ROOT,OUT,doc

GRAINS={'d':30,'w':20,'m':12,'q':8}
MONTHS=['янв','фев','мар','апр','май','июн','июл','авг','сен','окт','ноя','дек']

def only(rows,section):
    matches=[r for r in rows if r['section']==section]
    assert len(matches)==1,(section,len(matches))
    return matches[0]

def expected_series(rows,grain):
    by={}
    for row in rows:
        if row['section']=='ts':
            for line in str(row['k']).splitlines():
                p=[int(x or 0) for x in line.split('|')]
                by[p[0]]=dict(k=p[0],u=p[1],nu=p[2],re=p[3],v=p[4])
    return [by.get(k,dict(k=k,u=0,nu=0,re=0,v=0)) for k in range(GRAINS[grain]-1,-1,-1)]

def date_labels(rows,grain):
    md=date.fromisoformat(only(rows,'md')['k'])
    result=[]
    for k in range(GRAINS[grain]-1,-1,-1):
        if grain=='d': result.append(str((md-timedelta(days=k)).day))
        elif grain=='w': result.append('W'+str((md-timedelta(days=md.weekday()+7*k)).isocalendar().week))
        elif grain=='m': result.append(MONTHS[(md.month-1-k)%12])
        else: result.append('Q'+str(((md.month-1)//3-k)%4+1))
    return result

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('fixtures',type=Path)
    args=ap.parse_args()
    meta=json.loads((args.fixtures/'metadata.json').read_text())
    assert meta['clickhouse'].startswith('24.8.'),meta['clickhouse']
    for kind,name in [('head','3. SQL — шапка.sql'),('cat','5. SQL — каталог.sql'),('one','7. SQL — панель.sql')]:
        assert meta['source_sha256'][kind]==hashlib.sha256((OUT/name).read_bytes()).hexdigest(), 'Stale SQL fixture '+kind
    fixture={g:{p:json.loads((args.fixtures/g/(p+'.json')).read_text()) for p in ['head','cat','one']} for g in GRAINS}
    scripts={p:(OUT/n).read_text() for p,n in [('head','4. JS — весь отчёт.js'),('cat','6. JS — загрузчик каталога.js'),('one','8. JS — загрузчик панели.js')]}
    source_one=(ROOT/'Виджеты/pa-one.chart.js').read_text()
    source_cat=(ROOT/'Виджеты/pa-reports-body.chart.js').read_text()
    with sync_playwright() as p:
        browser=p.chromium.launch(executable_path='/usr/bin/chromium',headless=True)
        page=browser.new_page(viewport={'width':1600,'height':1100})
        errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
        page.set_content('<html><body style="margin:0"><iframe name="head" sandbox="allow-scripts" style="width:100%;height:1080px;border:0"></iframe><iframe name="cat" sandbox="allow-scripts" style="height:2px;width:2px;opacity:0"></iframe><iframe name="one" sandbox="allow-scripts" style="height:2px;width:2px;opacity:0"></iframe><script>window.emits=[];addEventListener("message",function(e){if(e.data.type==="TEST_EMIT")emits.push(e.data)});</script></body></html>')
        for part in ['cat','one','head']:
            page.locator('iframe[name="'+part+'"]').evaluate('(el,html)=>el.srcdoc=html',doc(part,scripts[part],fixture['d'][part]))
        frame=page.frame(name='head');frame.wait_for_selector('.pa-next-ready')
        references=browser.new_page(viewport={'width':1600,'height':1100})
        references.on('pageerror',lambda e:errors.append(str(e)))
        references.set_content('<iframe name="refone" sandbox="allow-scripts"></iframe><iframe name="refcat" sandbox="allow-scripts"></iframe>')
        for grain in GRAINS:
            if grain!='d':
                frame.locator('[data-pa-next-host="head"] [data-grain="'+grain+'"]').click()
                masks=frame.evaluate('window.__paNext.masks')
                expected_mask={'period_param':[grain]}
                assert {f['column']:f['value'] for f in masks['head'] if not f['column'].startswith('pa_next_')}==expected_mask
                for part in ['cat','one']:
                    incoming=copy.deepcopy(fixture[grain][part])
                    for row in incoming:
                        if row['section']=='pa_next_request':
                            source=row['g'];token='pa_next_'+source+'_req'
                            row['k']=next((f['value'][0] for f in masks[source] if f['column']==token),'')
                    # Every non-protocol row is byte-for-byte identical to the actual query fixture.
                    assert [r for r in incoming if r['section']!='pa_next_request']==[r for r in fixture[grain][part] if r['section']!='pa_next_request']
                    page.frame(name=part).evaluate('(payload)=>{data=payload.rows;'+scripts[part]+'}',{'rows':incoming})
                frame.wait_for_selector('.pa-next-ready')
            assert 'on' in (frame.locator('[data-pa-next-host="head"] [data-grain="'+grain+'"]').get_attribute('class') or '').split()
            actual=fixture[grain]['one']
            assert only(actual,'area')['parent']==grain
            total=[int(x or 0) for x in only(actual,'total')['k'].split('|')]
            numbers=frame.locator('.pone-kpis .pone-k-val').all_text_contents()
            digits=lambda text:int(re.sub(r'\D','',text))
            assert digits(numbers[0])==total[0],(grain,'users',numbers[0],total[0])
            assert digits(numbers[4])==total[10],(grain,'mau',numbers[4],total[10])
            graph=frame.locator('[data-pa-next-host="one"] [data-dyn="users"]')
            assert graph.get_attribute('data-grain')==grain
            buckets=json.loads(graph.get_attribute('data-bk'))
            assert [{k:b[k] for k in ['k','u','nu','re','v']} for b in buckets]==expected_series(actual,grain),(grain,buckets)
            axis=frame.locator('svg[aria-label="Пользователи по периодам"] text[font-size="10.5"][font-weight]').all_text_contents()
            assert axis==date_labels(actual,grain),(grain,axis,date_labels(actual,grain))
            for part,code in [('one',source_one),('cat',source_cat)]:
                region=frame.locator('[data-pa-next-host="'+part+'"]')
                size=region.bounding_box()
                el=references.locator('iframe[name="ref'+part+'"]')
                el.evaluate('(el,size)=>{el.style.width=size.width+"px";el.style.height=size.height+"px";el.style.border="0"}',size)
                el.evaluate('(el,html)=>el.srcdoc=html',doc('reference',code,fixture[grain][part]))
                ref=references.frame(name='ref'+part)
                selector='.pone-kpis' if part=='one' else '.prb-cat'
                ref.wait_for_selector(selector)
                assert frame.locator(selector).inner_text()==ref.locator(selector).inner_text(),(grain,part,'changed renderer output')
            assert not errors,errors
            print('PASS actual CH24.8 '+grain+': KPI users='+str(total[0])+', MAU='+str(total[10])+', '+str(len(buckets))+' exact SQL buckets, calendar axis, original KPI/catalogue render equality',flush=True)
            page.screenshot(path='/tmp/pa-next-ui-sql-'+grain+'.png')
        browser.close()
if __name__=='__main__':main()
