"""Encoding-independent Unicode operations for the GP acceleration paragraph.

The punctuation set is inherited verbatim from the reviewed CH 24.8 oracle.
Match UTF-8 hex instead of chr(codepoint): GP may use SQL_ASCII or WIN1251.
FIO packing also operates on delimited UTF-8 bytes, preserving the old wire format.
"""
import re

CYRILLIC = 'АБВГДЕЁЖЗИЙКЛМНОПРСТУФХЦЧШЩЪЫЬЭЮЯабвгдеёжзийклмнопрстуфхцчшщъыьэюя'
COMPACT = 'abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789!#$%'
PU = re.compile(r'with pu as \(.*?unnest\(array\[(.*?)\]\) c\s*\)', re.S)


def _alternatives(items):
    return items[0] if len(items) == 1 else '(?:' + '|'.join(items) + ')'


def build_pattern(codepoints):
    """Compile an exact set of UTF-8 byte sequences into a short ASCII regex."""
    trie = {}
    for point in sorted(set(codepoints)):
        node = trie
        for digit in chr(point).encode('utf-8').hex():
            node = node.setdefault(digit, {})
        node[''] = None

    def emit(node):
        if '' in node:
            if len(node) != 1:
                raise ValueError('UTF-8 sequences must be prefix-free')
            return ''
        by_suffix = {}
        for digit, child in sorted(node.items()):
            by_suffix.setdefault(emit(child), []).append(digit)
        return _alternatives([
            (digits[0] if len(digits) == 1 else '[' + ''.join(digits) + ']') + suffix
            for suffix, digits in by_suffix.items()
        ])

    return '^(?:' + emit(trie) + ')*$'


def pack_fio(expression):
    """Same Cyrillic compact encoding, safe even for UTF-8 text in SQL_ASCII.

    Each byte gets a ':' delimiter before matching/replacement. Without it,
    a Cyrillic hex sequence could match at an odd nibble offset in other text.
    All replacements produce ASCII bytes, so they cannot create a new Cyrillic
    match. Only chr() in the Python generator interprets Unicode codepoints.
    """
    if len(CYRILLIC) != len(COMPACT) or len(set(CYRILLIC)) != len(CYRILLIC):
        raise ValueError('Invalid Cyrillic wire alphabet')
    escaped = expression
    cyr = '(?:d0:(?:81|[9ab][0123456789abcdef]):|d1:(?:8[0123456789abcdef]|91):)'
    run = '(' + cyr + '(?:' + cyr + '|20:)*)'
    value = "regexp_replace(encode(convert_to(" + escaped + ", 'UTF8'), 'hex'), '(..)', E'\\\\1:', 'g')"
    value = "regexp_replace(" + value + ", '" + run + "', E'60:\\\\1" + "60:', 'g')"
    for source, target in zip(CYRILLIC, COMPACT):
        source_bytes = ''.join(f'{byte:02x}:' for byte in source.encode('utf-8'))
        target_byte = f'{ord(target):02x}:'
        value = "replace(" + value + ", '" + source_bytes + "', '" + target_byte + "')"
    return "convert_from(decode(replace(" + value + ", ':', ''), 'hex'), 'UTF8')"


def rewrite_acceleration(text):
    matches = list(PU.finditer(text))
    if len(matches) != 2:
        raise ValueError('Expected viewer and staff Unicode sets')
    sets = [tuple(map(int, re.findall(r'\d+', m[1]))) for m in matches]
    if sets[0] != sets[1] or len(set(sets[0])) != len(sets[0]):
        raise ValueError('Unicode sets differ or contain duplicates')
    pattern = build_pattern(sets[0])
    comment = (
        'with pu as (\n'
        '    -- Exact CH 24.8 whitespace/punctuation rule, matched on UTF-8 hex.\n'
        '    -- ASCII-only pattern works in UTF8, WIN1251 and SQL_ASCII databases.\n'
        '    -- Generated by tools/parallel/unicode_empty.py; no GP chr(codepoint).\n'
        "    select '" + pattern + "'::text as re\n)"
    )
    text = PU.sub(lambda _: comment, text)
    text, count = re.subn(r'\b(a[34567]_?) ~ pu\.re',
                          lambda m: "encode(convert_to(" + m[1] + ", 'UTF8'), 'hex') ~ pu.re", text)
    if count != 10:
        raise ValueError(f'Expected ten organisation checks, got {count}')
    # Match only the two inherited FIO packing expressions; preserve ASCII
    # delimiter escaping and every surrounding field/code/aggregation verbatim.
    old = re.compile(r"translate\(regexp_replace\((replace\(replace\(replace\(replace\(translate\(o\.fio, .*?), '\(\[А-Яа-яЁё\]\[А-Яа-яЁё \]\*\)', E'[^']*', 'g'\), '" + CYRILLIC + "', '" + re.escape(COMPACT) + r"'\)")
    text, count = old.subn(lambda m: pack_fio(m[1]), text)
    if count != 2:
        raise ValueError(f'Expected two FIO packers, got {count}')
    return text
